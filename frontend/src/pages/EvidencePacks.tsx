import { useState } from 'react';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { Loader2 } from 'lucide-react';
import { toast } from 'sonner';
import { errDetail } from '@/lib/errors';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { EmptyState, PageHeader, Pill } from '@/components/redesign/primitives';
import { FieldRow, SettingsCard, inputClass, warnCalloutClass } from '@/components/redesign-local/groupD/settingsForm';
import { evidencePackApi, type EvidencePack, type VerifyReport } from '@/api/compliance';
import { WorkspacePicker } from '@/components/compliance/WorkspacePicker';
import { useComplianceWorkspace } from '@/components/compliance/useComplianceWorkspace';
import { dayEnd, dayStart, defaultPeriod, fmtBytes, fmtDate, fmtDay } from '@/components/compliance/helpers';

const PACK_TONE = { queued: 'neutral', building: 'butter', ready: 'mint', failed: 'peach' } as const;

function PackRow({ pack, onDownload, busy }: { pack: EvidencePack; onDownload: () => void; busy: boolean }) {
    const [open, setOpen] = useState(false);
    return (
        <li className="flex flex-col gap-2 py-3">
            <div className="flex flex-wrap items-center gap-3">
                <Pill tone={PACK_TONE[pack.status]}>{pack.status}</Pill>
                <div className="min-w-0 flex-1 text-sm">
                    <span className="font-semibold text-ink">{fmtDay(pack.period_start)} to {fmtDay(pack.period_end)}</span>
                    <span className="block text-xs text-ink-soft">
                        #{pack.id} · requested by {pack.requested_by ?? 'unknown'} · {fmtDate(pack.created_at)}
                        {pack.status === 'ready' && <> · {pack.file_count} files · {fmtBytes(pack.size_bytes)}</>}
                    </span>
                    {pack.error && <span className="block text-xs text-ink-soft">{pack.error}</span>}
                </div>
                {pack.status === 'ready' && (
                    <>
                        <Button size="sm" variant="outline" onClick={() => setOpen((o) => !o)}>{open ? 'Hide contents' : 'Show contents'}</Button>
                        <Button size="sm" disabled={busy} onClick={onDownload}>Download pack</Button>
                    </>
                )}
            </div>
            {open && (
                <div className="flex flex-col gap-2 rounded-2xl bg-background p-3">
                    {pack.sha256 && <p className="break-all font-mono text-[11px] text-ink-soft">zip sha256 {pack.sha256}</p>}
                    {pack.manifest_signature && <p className="break-all font-mono text-[11px] text-ink-soft">manifest HMAC-SHA256 {pack.manifest_signature}</p>}
                    <ul className="flex flex-col text-xs">
                        {pack.files.map((f) => (
                            <li key={f.path} className="flex flex-wrap justify-between gap-2 border-t border-border py-1 first:border-t-0">
                                <span className="font-mono text-ink">{f.path}</span>
                                <span className="text-ink-soft">{fmtBytes(f.size)}</span>
                            </li>
                        ))}
                    </ul>
                </div>
            )}
        </li>
    );
}

function VerifyResult({ report }: { report: VerifyReport }) {
    const problems = [
        ...(report.errors ?? []),
        ...(report.mismatched ?? []).map((p) => `changed: ${p}`),
        ...(report.missing ?? []).map((p) => `missing: ${p}`),
        ...(report.unexpected ?? []).map((p) => `not in the manifest: ${p}`),
    ];
    return (
        <div className={report.verified ? 'rounded-2xl border border-border bg-white px-4 py-3 text-sm' : warnCalloutClass} role="status">
            <div className="flex flex-wrap items-center gap-2">
                <Pill tone={report.verified ? 'mint' : 'peach'}>{report.verified ? 'Verified' : 'Not verified'}</Pill>
                <span className="text-ink">
                    Signature {report.signature_valid ? `valid (${report.key === 'previous' ? 'an earlier key' : 'this instance\'s key'})` : 'not valid'}
                    {report.files_checked !== undefined && <> · {report.files_checked} file(s) checked</>}
                </span>
            </div>
            {report.workspace_name && (
                <p className="mt-1 text-xs text-ink-soft">
                    Pack #{report.pack_id} for {report.workspace_name}
                    {report.period && <>, {fmtDay(report.period.start)} to {fmtDay(report.period.end)}</>}
                    {report.generated_by?.email && <>, generated by {report.generated_by.email}</>} {report.generated_at && <>on {fmtDate(report.generated_at)}</>}
                </p>
            )}
            {problems.length > 0 && (
                <ul className="mt-2 list-disc pl-5 text-xs text-ink">
                    {problems.slice(0, 30).map((p) => <li key={p}>{p}</li>)}
                </ul>
            )}
        </div>
    );
}

/**
 * Evidence packs (WP13a): one signed zip per workspace and period for an
 * auditor. Workspace admins only — the server enforces it.
 */
export default function EvidencePacks() {
    const qc = useQueryClient();
    const { workspaces, workspaceId, setWorkspaceId } = useComplianceWorkspace();
    const initial = defaultPeriod();
    const [start, setStart] = useState(initial.start);
    const [end, setEnd] = useState(initial.end);
    const [zip, setZip] = useState<File | null>(null);
    const [manifest, setManifest] = useState<File | null>(null);
    const [report, setReport] = useState<VerifyReport | null>(null);

    const packs = useQuery({
        queryKey: ['evidence-packs', workspaceId],
        queryFn: () => evidencePackApi.list(workspaceId!),
        enabled: workspaceId !== null,
        // Poll while something is building; stop once everything settled.
        refetchInterval: (q) => (q.state.data?.some((p) => p.status === 'queued' || p.status === 'building') ? 3000 : false),
    });
    const build = useMutation({
        mutationFn: () => evidencePackApi.create(workspaceId!, dayStart(start), dayEnd(end)),
        onSuccess: () => { toast.success('Building the pack — it appears below when ready'); qc.invalidateQueries({ queryKey: ['evidence-packs', workspaceId] }); },
        onError: (e) => toast.error(errDetail(e)),
    });
    const download = useMutation({
        mutationFn: (id: number) => evidencePackApi.download(id),
        onSuccess: (r) => {
            const a = document.createElement('a');
            a.href = r.url;
            a.download = r.filename;
            a.rel = 'noopener';
            document.body.appendChild(a);
            a.click();
            a.remove();
        },
        onError: (e) => toast.error(errDetail(e)),
    });
    const verify = useMutation({
        mutationFn: () => evidencePackApi.verify(zip!, manifest),
        onSuccess: setReport,
        onError: (e) => { setReport(null); toast.error(errDetail(e)); },
    });

    const problem = !start || !end ? 'Pick both dates' : start > end ? 'The start must be before the end' : null;

    return (
        <div className="flex flex-col gap-5">
            <PageHeader
                title="Evidence packs"
                subtitle="One zip for an auditor: the audit log and its chain check, access reviews, controls and exceptions, data policies, security findings (SARIF) and restore drills, with a signed manifest of every file."
                actions={<WorkspacePicker workspaces={workspaces} value={workspaceId} onChange={setWorkspaceId} />}
            />

            <SettingsCard
                labelledBy="pack-build"
                title="Build a pack"
                description="Covers this workspace only. Building runs in the background and can take a minute for a large workspace."
                footer={
                    <>
                        <Button disabled={!!problem || build.isPending || workspaceId === null} onClick={() => build.mutate()}>
                            {build.isPending && <Loader2 className="h-4 w-4 animate-spin" />} Build evidence pack
                        </Button>
                        {problem && <span className="text-xs text-ink-soft" role="status">{problem}</span>}
                    </>
                }
            >
                <div className="flex flex-col divide-y divide-border">
                    <FieldRow label="From" htmlFor="pack-start" hint="Start of the first day, UTC.">
                        <Input id="pack-start" type="date" className={inputClass} value={start} max={end} onChange={(e) => setStart(e.target.value)} />
                    </FieldRow>
                    <FieldRow label="To" htmlFor="pack-end" hint="End of the last day, UTC.">
                        <Input id="pack-end" type="date" className={inputClass} value={end} min={start} max={defaultPeriod().end} onChange={(e) => setEnd(e.target.value)} />
                    </FieldRow>
                </div>
            </SettingsCard>

            <SettingsCard labelledBy="pack-list" title="Packs" description="Downloads use a link that works for five minutes; every download is recorded in the audit trail.">
                {packs.isLoading ? (
                    <p className="flex items-center gap-2 text-sm text-ink-soft"><Loader2 className="h-4 w-4 animate-spin" /> Loading…</p>
                ) : packs.isError ? (
                    <p className="text-sm text-ink-soft">{errDetail(packs.error)}</p>
                ) : (packs.data ?? []).length === 0 ? (
                    <EmptyState title="No packs yet" />
                ) : (
                    <ul className="flex flex-col divide-y divide-border">
                        {(packs.data ?? []).map((p) => (
                            <PackRow key={p.id} pack={p} busy={download.isPending} onDownload={() => download.mutate(p.id)} />
                        ))}
                    </ul>
                )}
            </SettingsCard>

            <SettingsCard
                labelledBy="pack-verify"
                title="Verify a pack"
                description="Recomputes every file's SHA-256 and checks the manifest signature. Any edited, added or removed file — or an edited manifest — fails."
                footer={
                    <Button variant="outline" disabled={!zip || verify.isPending} onClick={() => verify.mutate()}>
                        {verify.isPending && <Loader2 className="h-4 w-4 animate-spin" />} Verify pack
                    </Button>
                }
            >
                <div className="flex flex-col gap-3">
                    <label className="flex flex-col gap-1.5 text-sm font-medium text-ink">
                        Pack (.zip)
                        <input type="file" accept=".zip,application/zip" className="text-sm" onChange={(e) => { setZip(e.target.files?.[0] ?? null); setReport(null); }} />
                    </label>
                    <label className="flex flex-col gap-1.5 text-sm font-medium text-ink">
                        Separate manifest.json (optional — otherwise the one inside the zip is used)
                        <input type="file" accept=".json,application/json" className="text-sm" onChange={(e) => { setManifest(e.target.files?.[0] ?? null); setReport(null); }} />
                    </label>
                    {report && <VerifyResult report={report} />}
                </div>
            </SettingsCard>
        </div>
    );
}
